"""Render `paper/references.bib` into the manuscript's reference section.

`references.bib` is the single source of truth. The manuscript is markdown, so a generated
numbered list keeps the two in sync without a LaTeX pipeline, and keeps `verify_all.py` able
to check that every cited key exists.

Usage:
    python src/analysis/p34_bib_to_markdown.py            # write the section
    python src/analysis/p34_bib_to_markdown.py --check    # fail if out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from bench_env import PAPER  # noqa: E402

BIB = PAPER / "references.bib"
OUT = PAPER / "12-references-draft.md"

HEADER = """<!-- GENERATED from paper/references.bib by src/analysis/p34_bib_to_markdown.py.
     Edit the .bib, then re-run the script. Do not edit this file. -->

# 参考文献

**本表只收录已核对原文的来源。** 每一条的标题、作者、年份与发表处均以**抓取到的一手页面**
为准（arXiv 条目经 `export.arxiv.org/api/query` 一次性核验 16 条），不凭记忆填写。

> **为什么把这条规则写在表前**：arXiv 对「有不可辩驳证据表明作者未核对 LLM 生成结果」的投稿，
> 罚则为**一年封禁**，而其点名的第一个例子就是**幻觉参考文献**。本项目的来源分级
> （`recon\\R2-verified-externals.md`）本就规定第三方转述不得作为证据；参考文献适用同一标准。
"""


def parse_bib(text: str) -> list[dict]:
    entries = []
    for block in re.findall(r"@(\w+)\{([^,]+),(.*?)\n\}", text, re.S):
        kind, key, body = block
        fields: dict[str, str] = {}
        for m in re.finditer(r"(\w+)\s*=\s*\{(.*?)\}\s*,?\s*\n", body + "\n", re.S):
            fields[m.group(1).lower()] = re.sub(r"\s+", " ", m.group(2)).strip()
        entries.append({"kind": kind, "key": key.strip(), **fields})
    return entries


def plain(s: str) -> str:
    """Strip the LaTeX that is correct in a .bib and wrong in markdown.

    `{FrugalGPT}` braces protect capitalisation in BibTeX and must not appear in rendered
    text; `{\\~n}` and friends are accent macros. Leaving them in produces a reference list
    that looks machine-generated, which is precisely the impression this paper cannot afford.
    """
    for macro, char in (("\\~n", "ñ"), ("\\v{c}", "č"), ("\\v{s}", "š"), ("\\v{z}", "ž"),
                        ("\\'c", "ć"), ("\\'i", "í"), ("\\'e", "é"), ("\\'a", "á"),
                        ("\\'o", "ó"), ("\\'u", "ú"), ("\\~a", "ã"), ('\\"u', "ü"),
                        ("\\`e", "è"), ("\\^e", "ê")):
        s = s.replace("{" + macro + "}", char).replace(macro, char)
    s = re.sub(r"\{([^{}]*)\}", r"\1", s)      # {FrugalGPT} -> FrugalGPT
    s = s.replace("~", " ").replace("--", "–")
    return re.sub(r"\s+", " ", s).strip()


def render(e: dict) -> str:
    authors = plain(e.get("author", ""))
    # "A and B and C" -> "A, B, C"; keep "and others" readable
    authors = authors.replace(" and others", " et al.").replace(" and ", ", ")
    authors = re.sub(r"\s+", " ", authors).strip()

    title = plain(e.get("title", ""))
    year = e.get("year", "")
    venue = plain(e.get("booktitle") or e.get("journal") or "")
    if not venue and e.get("eprint"):
        venue = f"arXiv preprint arXiv:{e['eprint']}"

    bits = [f"**{authors}** ({year}).", f"{title}."]
    if venue:
        bits.append(f"*{venue}.*")
    if e.get("url"):
        bits.append(f"<{e['url']}>")
    return " ".join(bits)


def build() -> str:
    entries = parse_bib(BIB.read_text(encoding="utf-8"))
    entries.sort(key=lambda e: (e.get("author", "").split(",")[0].lower(),
                                e.get("year", "")))
    lines = [HEADER, ""]
    for i, e in enumerate(entries, 1):
        lines.append(f"[{i}] {render(e)}")
        lines.append("")
    # a key index so in-text citations can be written as [key] and resolved mechanically
    lines.append("---")
    lines.append("")
    lines.append("**引用键索引**（正文以 `[@key]` 引用，本表由脚本从 `.bib` 生成）：")
    lines.append("")
    for i, e in enumerate(entries, 1):
        lines.append(f"- `{e['key']}` → [{i}]")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    rendered = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print("STALE: 12-references-draft.md differs from references.bib")
            print("       re-run without --check to regenerate")
            return 1
        print(f"fresh: {len(parse_bib(BIB.read_text(encoding='utf-8')))} entries")
        return 0
    OUT.write_text(rendered, encoding="utf-8")
    n = len(parse_bib(BIB.read_text(encoding="utf-8")))
    print(f"wrote {OUT.name}: {n} verified references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
