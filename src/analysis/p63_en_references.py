"""Generate the ENGLISH rendering of the reference list from the same references.bib.

WHY THIS EXISTS
    `paper/en/_assemble.py` appends the reference list, which is generated from
    `references.bib` and is the single source of truth -- but it was generated in Chinese, so
    `verify_all.py` I2 warned that the English manuscript contained untranslated Chinese.

    The entries themselves are language-neutral: author names, titles and venues are already
    English. Only the header and the two preamble paragraphs are Chinese. So this reuses
    `p34_bib_to_markdown`'s parser and renderer rather than reimplementing them, and supplies
    an English header and preamble. One .bib, two renderings, no drift.

    The preamble is kept rather than dropped because it states a rule the list depends on --
    that every entry was checked against a fetched primary source, and why that matters. The
    English says the same thing.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from bench_env import PAPER  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from p34_bib_to_markdown import BIB, parse_bib, render  # noqa: E402

OUT = PAPER / "en" / "12-references.md"

HEADER = """<!-- GENERATED from paper/references.bib by src/analysis/p63_en_references.py.
     Edit the .bib, then re-run. Do not edit this file. -->

# References

**This list contains only sources whose original was checked.** Every entry's title, authors,
year and venue is taken from a **fetched primary source** (the arXiv entries were verified in
one pass against `export.arxiv.org/api/query`), never from memory.

> **Why this rule is stated before the list**: arXiv's penalty for a submission containing
> "incontrovertible evidence that the authors did not check the results of LLM generation" is a
> **one-year ban**, and the first example it names is **hallucinated references**. This project's
> source tiers (`recon/R2-verified-externals.md`) already forbid third-party relay as evidence;
> the reference list is held to the same standard.
"""


def build() -> str:
    entries = parse_bib(BIB.read_text(encoding="utf-8"))
    entries.sort(key=lambda e: (e.get("author", "").split(",")[0].lower(),
                                e.get("year", "")))
    lines = [HEADER, ""]
    for i, e in enumerate(entries, 1):
        lines.append(f"[{i}] {render(e)}")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("**Key index** (the text cites as `[@key]`; this table is generated from the "
                 "`.bib`):")
    lines.append("")
    for i, e in enumerate(entries, 1):
        lines.append(f"- `{e['key']}` -> [{i}]")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    rendered = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print("STALE: en/12-references.md differs from references.bib")
            return 1
        print("fresh: en/12-references.md")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    n = len(parse_bib(BIB.read_text(encoding="utf-8")))
    print(f"wrote en/{OUT.name}: {n} verified references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
