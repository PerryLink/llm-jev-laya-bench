"""P22f REPAIR: the ignore-SUPERSEDED rate is computed on a structurally impossible denominator.

THE DEFECT
----------
`p22_chain_audit.py` builds each item's option set as

    opts = {truth, alt, truth + 6, truth - 12, truth * 2}
    opts = [v for v in sorted(opts) if v > 0][:4]

`alt` is the value a model reaches by IGNORING the SUPERSEDED marks -- the single error
mode the metric is supposed to measure. Two mechanisms silently remove it from the offered
options:

  MECHANISM A (2 of 68): `alt <= 0` -> dropped by the `v > 0` filter.
      CH-K16-000 (alt=-18), CH-K16-008 (alt=-48)
  MECHANISM B (5 of 68): `alt` is the LARGEST candidate, and `sorted(...)[:4]` keeps the
      four SMALLEST -> `alt` is truncated. Note the irony: `truth * 2` is also a candidate
      and is often nearly equal to `alt`, so the item keeps a *doubled* decoy while losing
      the *exact* ignore-superseded answer.
      CH-K4-005 (3816 vs 3792), CH-K4-015 (210 vs 204), CH-K4-018 (456 vs 432),
      CH-K8-021 (3972 vs 1992), CH-K16-012 (15228 vs 7716)

For those 7 items the model CANNOT express the error, yet `run()` divides by every row that
carries a judgement. The rate is therefore attenuated by construction: the ceiling is
61/68 = 0.897, not 1.0. The paper's prose already states this (draft `08`, item 4), but the
MACHINE-READABLE field in the artifact still reports the attenuated number, so anything
reading the JSON inherits the error.

WHAT THIS SCRIPT DOES
---------------------
1. Rebuilds the published item set and PROVES the reconstruction is faithful by asserting
   the rebuilt `truth` equals the recorded `truth` for every row of every artifact.
2. Backfills `alt_in_options` onto every row (True only where `alt` really was offered).
3. Recomputes the rate on the eligible denominator and records BOTH denominators, so the
   attenuated figure is still visible and the provenance of each is explicit.
4. Writes the repaired artifacts in place, after backing up the originals.

The pre-fix pilot `P22-chain-audit.json` used the BUGGY `simulate()` (no parity replay), so
its `alt` values -- and therefore its option sets -- differ from the fixed generator's. It
is reconstructed with a faithful replay of the pre-fix logic (`legacy_items`), asserted
against its own recorded truths, and repaired on the same terms.

It makes NO model calls: the item set is generated by a seeded RNG, so the option sets are
recoverable exactly and the repair is arithmetic, not a re-measurement. Re-running the
battery instead would have changed every published number for no gain in validity.

The generator fix in `p22_chain_audit.py` (making `alt` always offered when positive) is
applied SEPARATELY and only affects FUTURE runs -- deliberately not retro-applied here,
because changing the option sets would invalidate the published draws.
"""

from __future__ import annotations

import importlib.util
import json
import random
import shutil
from pathlib import Path

ROOT = Path(r"D:\Projects\llm-jev-laya-bench")
RESULTS = ROOT / "results"

FIXED_ARTIFACTS = ["P22b-fixed-r1.json", "P22b-fixed-r2.json", "P22b-fixed-r3.json"]
LEGACY_ARTIFACT = "P22-chain-audit.json"


def load_generator():
    spec = importlib.util.spec_from_file_location(
        "p22_chain_audit", ROOT / "src" / "items" / "p22_chain_audit.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def simulate_prefix_bug(mod, steps: list[dict], ignore_superseded: bool) -> int:
    """Deprecated shim -- delegate to the module so the logic lives in exactly one place."""
    return mod.simulate_prefix_fix(steps, ignore_superseded)


def legacy_items(mod) -> list[dict]:
    """The 69-item pre-fix pilot: pre-round-5 option construction AND pre-M-20 simulate."""
    out = mod.build_items(legacy_options=True, legacy_simulate=True)
    for it in out:                        # criteria only; `state` is not needed to repair
        it["criteria"] = it["criteria"]
    return out


def repair_one(name: str, items: dict, *, legacy: bool) -> dict:
    path = RESULTS / name
    doc = json.loads(path.read_text(encoding="utf-8"))
    rows = doc["rows"]

    # ---- STEP 1: prove the reconstruction is faithful -----------------------------------
    mismatched = [r["item_id"] for r in rows
                  if r["item_id"] not in items
                  or items[r["item_id"]]["truth"] != r["truth"]]
    if mismatched:
        raise AssertionError(
            f"{name}: reconstruction is NOT faithful; truth mismatch on {len(mismatched)} "
            f"rows: {mismatched[:8]}. Refusing to backfill.")

    # ---- STEP 2: backfill alt_in_options ------------------------------------------------
    for r in rows:
        it = items[r["item_id"]]
        offered = set(it["criteria"].values())
        r["alt_in_options"] = str(it["alt_ignore_superseded"]) in offered

    eligible = [r for r in rows if r["alt_in_options"]]
    entry: dict = {
        "n_rows": len(rows),
        "n_alt_offered": len(eligible),
        "n_alt_not_offered": len(rows) - len(eligible),
        "rate_ceiling": round(len(eligible) / len(rows), 4),
        "legacy_option_sets": legacy,
    }

    for arm in ("llm", "laya"):
        answered = [r for r in rows if r.get(f"{arm}_correct") is not None]
        eligible_answered = [r for r in answered if r["alt_in_options"]]
        # A row can only carry the flag if `alt` was among the options (the flag is set by
        # comparing the chosen option's VALUE to `alt`), so hits are identical either way;
        # only the denominator changes. That is exactly why the defect attenuates and never
        # inflates the rate.
        hits = sum(1 for r in answered if r.get(f"{arm}_picked_ignore_superseded"))
        assert hits == sum(1 for r in eligible_answered
                           if r.get(f"{arm}_picked_ignore_superseded")), "hits not subset"
        old_n, new_n = len(answered), len(eligible_answered)
        old_rate = round(hits / old_n, 4) if old_n else None
        new_rate = round(hits / new_n, 4) if new_n else None

        s = doc["summary"]
        s[f"{arm}_picked_ignore_superseded_rate"] = new_rate          # corrected
        s[f"{arm}_picked_ignore_superseded_rate_eligible"] = new_rate
        s[f"{arm}_picked_ignore_superseded_hits"] = hits
        s[f"{arm}_picked_ignore_superseded_denominator"] = new_n
        s[f"{arm}_picked_ignore_superseded_rate_all_answered"] = old_rate
        s[f"{arm}_picked_ignore_superseded_denominator_all_answered"] = old_n
        entry[arm] = {"old_denominator": old_n, "old_rate": old_rate,
                      "new_denominator": new_n, "new_rate": new_rate, "hits": hits}

    doc["summary"]["alt_option_availability"] = {
        "n_rows": len(rows),
        "n_alt_offered": len(eligible),
        "n_alt_not_offered": len(rows) - len(eligible),
        "rate_ceiling": round(len(eligible) / len(rows), 4),
        "not_offered_item_ids": sorted(r["item_id"] for r in rows if not r["alt_in_options"]),
        "_note": (
            "The ignore-SUPERSEDED rate is defined only on items where the "
            "ignore-SUPERSEDED value was among the offered options. On the remaining items "
            "the error is unexpressible, so including them attenuates the rate by "
            "construction. Both denominators are retained: the `_eligible` fields are the "
            "corrected figures; the `_all_answered` fields are the attenuated ones written "
            "by earlier versions of this artifact."
        ),
    }
    doc["summary"]["_repair"] = (
        "alt_in_options backfilled by src/items/p22f_repair_denominator.py and the "
        "ignore-SUPERSEDED rate recomputed on the eligible denominator. No model calls were "
        "made and no judgement was altered: the item set is seeded, so the option sets were "
        "recovered exactly and verified against every recorded truth."
    )

    backup = path.with_suffix(".json.pre-repair")
    if not backup.exists():
        shutil.copy2(path, backup)
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False), encoding="utf-8")
    return entry


def repair() -> dict:
    mod = load_generator()
    report: dict = {
        "_generated_by": "src/items/p22f_repair_denominator.py",
        "_pure_derivation": True,
        "_why_no_instrument_record": (
            "This file makes NO measurement. It recomputes a denominator over artifacts that "
            "already carry instrument records, using a seeded item generator whose "
            "reconstruction is asserted against every recorded truth. There is therefore no "
            "instrument to attribute."),
        "artifacts": {},
    }

    fixed = {it["item_id"]: it for it in mod.build_items(legacy_options=True)}
    report["n_rebuilt_fixed"] = len(fixed)

    print("=== FIXED BATTERY (P22b, 3 draws, temperature pinned) ===")
    for name in FIXED_ARTIFACTS:
        e = repair_one(name, fixed, legacy=False)
        report["artifacts"][name] = e
        print(f"  {name:24s} rows={e['n_rows']} offered={e['n_alt_offered']} "
              f"ceiling={e['rate_ceiling']}")
        for arm in ("llm", "laya"):
            a = e[arm]
            print(f"      {arm.upper():4s} {a['old_rate']} ({a['hits']}/{a['old_denominator']})"
                  f"  ->  {a['new_rate']} ({a['hits']}/{a['new_denominator']})")

    legacy = {it["item_id"]: it for it in legacy_items(mod)}
    report["n_rebuilt_legacy"] = len(legacy)
    assert len(legacy) == 69, f"legacy rebuild gave {len(legacy)}, expected 69"

    print("\n=== PRE-FIX PILOT (P22, single draw, temperature NOT pinned) ===")
    e = repair_one(LEGACY_ARTIFACT, legacy, legacy=True)
    report["artifacts"][LEGACY_ARTIFACT] = e
    print(f"  {LEGACY_ARTIFACT:24s} rows={e['n_rows']} offered={e['n_alt_offered']} "
          f"ceiling={e['rate_ceiling']}")
    for arm in ("llm", "laya"):
        a = e[arm]
        print(f"      {arm.upper():4s} {a['old_rate']} ({a['hits']}/{a['old_denominator']})"
              f"  ->  {a['new_rate']} ({a['hits']}/{a['new_denominator']})")

    return report


if __name__ == "__main__":
    rep = repair()
    out = RESULTS / "P22f-ignore-superseded-denominator-repair.json"
    out.write_text(json.dumps(rep, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\nwritten: {out}")
